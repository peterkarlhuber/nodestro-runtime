#!/usr/bin/env python3
"""AC-7 (TABRION QA-21): this repository uses only the public API of Tabrion.

    python scripts/check_tabrion_api.py                    # check src, tests, scripts, examples
    python scripts/check_tabrion_api.py --export docs/api-consumers.md        # (re)write the used names
    python scripts/check_tabrion_api.py --check-export docs/api-consumers.md  # fail when it is stale
    python scripts/check_tabrion_api.py --surface ../tabrion/docs/api/surface.json  # compare with K10

The check reads every Python file with :mod:`ast` (nothing is imported or run) and refuses:

- ``import tabrion._x``, ``import tabrion.a._b``, ``from tabrion._x import y``, ``from tabrion.a import _y``;
- an attribute with a leading underscore on a name bound to Tabrion (``tabrion.postgres._pool``,
  ``roles._query`` after ``from tabrion.postgres import roles``), and ``getattr(<tabrion name>, "_x")``
  (attributes of objects that Tabrion returns are not tracked: the check is static);
- ``importlib.import_module("tabrion._x")`` and ``__import__("tabrion._x")`` with a constant name.

Names of the form ``__x__`` (``tabrion.__version__``) are public. When Tabrion is installed, every used
name must also be public there: a module, or a name in its module's ``__all__`` (document 04 of the Tabrion
plan). With ``--surface`` every used name must be in Tabrion's frozen API snapshot
(``docs/api/surface.json``, K10) or be a module of it.

The used names are written to ``docs/api-consumers.md`` (``--export``), the consumer side of Tabrion's
``docs/api-consumers.md``. Standard library only; the same file is used in tabrion-studio, axentra, orkexa
and nodestro-runtime (keep the copies identical). Exit codes: 0 clean, 1 findings or a stale export, 2 usage
errors.
"""

from __future__ import annotations

import argparse
import ast
from collections import defaultdict
from dataclasses import dataclass
import importlib
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PATHS = ("src", "tests", "scripts", "examples")
#: Directories that are never read.
SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "build", "dist", "__pycache__", ".tox", ".mypy_cache"}
HEADER = """# Tabrion API used by this repository

Generated by `python scripts/check_tabrion_api.py --export docs/api-consumers.md` (AC-7, TABRION QA-21);
do not edit. CI fails when this list is stale or when a private Tabrion name (`tabrion._*`, a `_` attribute)
is used.
"""


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.message}"


def _private(part: str) -> bool:
    return part.startswith("_") and not (part.startswith("__") and part.endswith("__"))


def _is_tabrion(dotted: str) -> bool:
    return dotted == "tabrion" or dotted.startswith("tabrion.")


class _Visitor(ast.NodeVisitor):
    def __init__(self, path: str) -> None:
        self.path = path
        self.findings: list[Finding] = []
        self.used: set[str] = set()
        #: local name -> dotted Tabrion name it is bound to.
        self.bound: dict[str, str] = {}

    def _use(self, dotted: str, node: ast.AST) -> None:
        parts = dotted.split(".")
        if any(_private(p) for p in parts[1:]):
            line = getattr(node, "lineno", 0)
            self.findings.append(Finding(self.path, line, f"private Tabrion name {dotted}"))
        else:
            self.used.add(dotted)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            if _is_tabrion(alias.name):
                self._use(alias.name, node)
                if alias.asname:
                    self.bound[alias.asname] = alias.name
                else:
                    self.bound["tabrion"] = "tabrion"
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        module = node.module or ""
        if node.level == 0 and _is_tabrion(module):
            if any(_private(p) for p in module.split(".")[1:]):
                self._use(module, node)
            else:
                for alias in node.names:
                    if alias.name == "*":
                        self.findings.append(Finding(self.path, node.lineno, f"star import from {module}"))
                        continue
                    dotted = f"{module}.{alias.name}"
                    self._use(dotted, node)
                    self.bound[alias.asname or alias.name] = dotted
        self.generic_visit(node)

    def _dotted(self, node: ast.AST) -> str | None:
        """The Tabrion name of ``tabrion.a.b`` or ``alias.b`` (``None`` when it is not one)."""
        if isinstance(node, ast.Name):
            return self.bound.get(node.id)
        if isinstance(node, ast.Attribute):
            base = self._dotted(node.value)
            return None if base is None else f"{base}.{node.attr}"
        return None

    def visit_Attribute(self, node: ast.Attribute) -> None:
        dotted = self._dotted(node)
        if dotted is not None:
            self._use(dotted, node)
            return  # the outermost attribute names the whole chain (``ast`` visits it first)
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        func = node.func
        name = func.id if isinstance(func, ast.Name) else func.attr if isinstance(func, ast.Attribute) else ""
        first = node.args[0] if node.args else None
        constant = first.value if isinstance(first, ast.Constant) and isinstance(first.value, str) else None
        if name in ("import_module", "__import__") and constant is not None and _is_tabrion(constant):
            self._use(constant, node)
        if name == "getattr" and len(node.args) >= 2 and isinstance(node.args[1], ast.Constant):
            base = self._dotted(node.args[0])
            attr = node.args[1].value
            if base is not None and isinstance(attr, str):
                self._use(f"{base}.{attr}", node)
        self.generic_visit(node)


def _files(paths: list[Path]) -> list[Path]:
    found: list[Path] = []
    for path in paths:
        if path.is_file() and path.suffix == ".py":
            found.append(path)
        elif path.is_dir():
            for file in sorted(path.rglob("*.py")):
                if not SKIP_DIRS.intersection(file.relative_to(path).parts):
                    found.append(file)
    return found


def scan_source(text: str, path: str = "<source>") -> tuple[list[Finding], set[str]]:
    """Findings and used Tabrion names of one file's source."""
    try:
        tree = ast.parse(text, filename=path)
    except SyntaxError as exc:
        return [Finding(path, exc.lineno or 0, f"cannot parse: {exc.msg}")], set()
    visitor = _Visitor(path)
    visitor.visit(tree)
    return visitor.findings, visitor.used


def check_source(source: str, filename: str = "<string>") -> list[str]:
    """Problems in one file's source (empty list: only public names)."""
    return [str(f) for f in scan_source(source, filename)[0]]


def scan(paths: list[Path], root: Path = ROOT) -> tuple[list[Finding], dict[str, set[str]]]:
    """Findings, and for every used Tabrion name the files that use it."""
    findings: list[Finding] = []
    used: dict[str, set[str]] = defaultdict(set)
    for file in _files(paths):
        rel = file.relative_to(root).as_posix() if file.is_relative_to(root) else file.as_posix()
        if rel == "scripts/check_tabrion_api.py":
            continue  # this file names private forms in its own documentation and probes
        found, names = scan_source(file.read_text(encoding="utf-8"), rel)
        findings += found
        for name in names:
            used[name].add(rel)
    return findings, dict(used)


def installed_check(names: set[str]) -> list[str]:
    """Names that are not public in the installed Tabrion (empty when Tabrion is not installed)."""
    if importlib.util.find_spec("tabrion") is None:
        return []
    problems = []
    for name in sorted(names):
        parts = name.split(".")
        for cut in range(len(parts), 0, -1):  # the longest importable module prefix
            module_name = ".".join(parts[:cut])
            try:
                module = importlib.import_module(module_name)
            except ImportError:
                continue
            rest = parts[cut:]
            if rest:
                public = getattr(module, "__all__", None)
                if public is not None and rest[0] not in public:
                    problems.append(f"{name}: {rest[0]} is not in {module_name}.__all__")
            break
    return problems


def surface_check(names: set[str], surface: Path) -> list[str]:
    """Names that are neither in the frozen API snapshot nor one of its modules."""
    keys = set(json.loads(surface.read_text(encoding="utf-8"))["names"])
    modules = {"tabrion"} | {k.rsplit(".", 1)[0] for k in keys}
    missing = sorted(name for name in names if name not in keys and name not in modules)
    return [f"{name}: not in {surface.name}" for name in missing]


def render(used: dict[str, set[str]]) -> str:
    lines = [HEADER]
    if not used:
        lines.append("This repository uses no Tabrion name yet.\n")
        return "\n".join(lines)
    lines += ["| Name | Used in |", "|---|---|"]
    for name in sorted(used):
        lines.append(f"| `{name}` | {', '.join(f'`{p}`' for p in sorted(used[name]))} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "paths", nargs="*", type=Path, help=f"files or directories (default: {', '.join(DEFAULT_PATHS)})"
    )
    parser.add_argument("--export", type=Path, help="write the list of used names (Markdown)")
    parser.add_argument("--check-export", type=Path, help="fail when this exported list is not current")
    parser.add_argument("--surface", type=Path, help="Tabrion's docs/api/surface.json (K10 snapshot)")
    args = parser.parse_args(argv)
    paths = args.paths or [ROOT / p for p in DEFAULT_PATHS if (ROOT / p).exists()]
    findings, used = scan(paths)
    problems = [str(f) for f in findings] + installed_check(set(used))
    if args.surface:
        if not args.surface.is_file():
            print(f"no such file: {args.surface}", file=sys.stderr)
            return 2
        problems += surface_check(set(used), args.surface)
    text = render(used)
    if args.export:
        args.export.write_text(text, encoding="utf-8")
    if args.check_export:
        current = args.check_export.read_text(encoding="utf-8") if args.check_export.is_file() else ""
        if current != text:
            problems.append(f"{args.check_export} is stale: run --export {args.check_export}")
    for problem in problems:
        print(problem)
    if problems:
        print(f"tabrion api check: {len(problems)} problem(s)")
    else:
        print(f"tabrion api check: ok ({len(used)} public name(s) used)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
