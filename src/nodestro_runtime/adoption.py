"""Taking content over into knowledge: only what a person chose, saw and confirmed.

Sources are input files of a run (also single files of a ZIP archive), result files,
results of single steps and proposals an agent made (``propose_knowledge`` or a step
configured to propose its result). Adoption has two steps:

1. :func:`check` reads every chosen item and returns what would be stored: name, format,
   whether knowledge can search it, a preview (texts can be edited), duplicates and similar
   files already in knowledge, the origin, and a *token* per item. Nothing is stored.
2. :func:`adopt` stores the items in the existing knowledge (:class:`~nodestro_runtime.knowledge.KnowledgeBase`,
   same store, same index) in the chosen collection, but only when the request is
   confirmed and every token still matches: the confirmation always refers to exactly
   the content that was shown, never to an agent or to starting a workflow.

Files identical to a knowledge file are not stored twice; similar texts are reported.
Adopted files keep their origin (workflow, step, run, source files, time, and whether the
content was extracted, generated by an agent or an unverified assumption). Knowledge is not
memory: nothing here writes to an agent's memory, and no agent gets a new file assigned,
so running and saved workflows see exactly what they saw before.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
from pathlib import PurePosixPath
import re
from typing import TYPE_CHECKING, Any, Literal

from pydantic import BaseModel, Field

from .engine import node_label
from .file_formats import FORMATS, FileFormatError, format_of_name
from .input_files import is_input_id
from .knowledge import KnowledgeFile
from .problems import NodestroError, Problem
from .reports import to_markdown
from .schemas import ContentKind, Run

if TYPE_CHECKING:
    from .workspace import Workspace

_PREVIEW = 6000
_MAX_TEXT = 500_000
_SIMILAR = 0.6
_KIND_TEXT = {
    "extracted": "Information extracted from the source files",
    "generated": "Conclusions generated by an AI agent; check them before relying on them",
    "assumption": "Unverified assumptions of an AI agent",
}
#: Media types the knowledge store accepts for text formats.
_TEXT_MEDIA = {
    "txt": "text/plain",
    "md": "text/markdown",
    "code": "text/plain",
    "csv": "text/csv",
    "json": "text/plain",
}


class AdoptionError(NodestroError):
    """Content cannot be taken over into knowledge."""


class AdoptSource(BaseModel):
    """One thing to take over."""

    kind: Literal["input", "result_file", "node_output", "proposal"]
    #: ``input``: the input file, and for a ZIP archive the path of one file in it.
    input_id: str | None = None
    path: str | None = None
    run_id: str | None = None
    #: ``result_file``: the result file of the run.
    file_id: str | None = None
    #: ``node_output`` and ``proposal``: the step.
    node_id: str | None = None
    proposal_id: str | None = None
    #: The name in knowledge (a sensible default when empty).
    title: str = ""
    #: Edited text (results and proposals only).
    text: str | None = None
    content_kind: ContentKind | None = None


class AdoptRequest(BaseModel):
    items: list[AdoptSource] = Field(min_length=1, max_length=100)
    #: The target collection: an existing one or a new name.
    collection: str = Field(min_length=1, max_length=120)
    description: str = ""


class AdoptConfirm(AdoptRequest):
    #: The person confirmed exactly these items.
    confirmed: bool = False
    #: The tokens :func:`check` returned, one per item, in order.
    tokens: list[str] = Field(default_factory=list)


class KnowledgeRef(BaseModel):
    id: str
    name: str
    collection: str = ""


class AdoptCheck(BaseModel):
    """What one item would become in knowledge."""

    name: str
    format: str | None = None
    size: int = 0
    #: Whether knowledge can search it (images, archives: stored only, not searchable).
    indexable: bool = True
    #: Results and proposals: the text can be edited before it is stored.
    editable: bool = False
    preview: str = ""
    text: str | None = None
    content_kind: ContentKind | None = None
    duplicate: KnowledgeRef | None = None
    similar: list[KnowledgeRef] = Field(default_factory=list)
    provenance: dict[str, str] = Field(default_factory=dict)
    token: str = ""
    problem: Problem | None = None


class AdoptOutcome(BaseModel):
    added: list[KnowledgeFile] = Field(default_factory=list)
    #: Items not stored: ``duplicate`` (already in knowledge) or a problem code.
    skipped: list[dict[str, Any]] = Field(default_factory=list)


class _Item(BaseModel):
    name: str
    data: bytes
    media_type: str | None
    format: str | None
    indexable: bool
    editable: bool
    text: str | None
    content_kind: ContentKind | None
    origin: str
    provenance: dict[str, str]
    #: Hash of the original bytes (an Office file is stored as Markdown, its original hash stays known).
    source_sha256: str


def _normalized(text: str) -> str:
    return " ".join(text.casefold().split())


def _text_hash(text: str) -> str:
    return hashlib.sha256(_normalized(text).encode("utf-8")).hexdigest()


def _words(text: str) -> set[str]:
    return set(re.findall(r"\w{3,}", text.casefold()))


def _run(ctx: Workspace, run_id: str | None) -> Run:
    run = ctx.runs.get(run_id or "") if run_id else None
    if run is None:
        raise AdoptionError("adopt.run_missing", "The run no longer exists", run=run_id or "")
    return run


def _base_provenance(ctx: Workspace, run: Run, node_id: str | None = None) -> dict[str, str]:
    names = ctx.inputs.names([item for item in run.file_ids if is_input_id(item)])
    names.update({item: ctx.knowledge.store.info(item).name for item in run.file_ids if item in ctx.knowledge.store})
    found = {
        "workflow": run.workflow_name,
        "workflow_id": run.workflow_id,
        "run": run.id,
        "run_at": (run.finished_at or run.created_at).isoformat(),
    }
    if names:
        found["sources"] = ", ".join(names.values())[:2000]
    if node_id:
        node = next((item for item in run.workflow.nodes if item.id == node_id), None)
        if node is not None:
            found["step"] = node_label(node)
            found["node"] = node_id
            if node.agent is not None:
                found["agent"] = node.agent.name
    return found


def _document(title: str, body: str, kind: ContentKind, provenance: dict[str, str]) -> str:
    """Generated content as Markdown with its origin on top (so readers and agents see it too)."""
    lines = [f"# {title}", ""]
    origin = f'Source: Nodestro workflow "{provenance.get("workflow", "")}", run {provenance.get("run", "")}'
    if provenance.get("step"):
        origin += f', step "{provenance["step"]}"'
    lines.append(f"> {origin}")
    lines.append(f"> Created: {provenance.get('run_at', '')}")
    lines.append(f"> Content: {_KIND_TEXT[kind]}")
    if provenance.get("sources"):
        lines.append(f"> Source files: {provenance['sources']}")
    return "\n".join(lines) + "\n\n" + body.strip() + "\n"


def _safe_title(title: str, fallback: str) -> str:
    text = re.sub(r"[\\/:*?\"<>|\x00-\x1f]+", " ", title).strip()
    return (text or fallback)[:150]


def _named(title: str, original: str) -> str:
    """A chosen name that keeps the original's extension (knowledge reads files by their extension)."""
    title = _safe_title(title, "")
    if not title:
        return original
    suffix = PurePosixPath(original).suffix
    return title if title.lower().endswith(suffix.lower()) else f"{title}{suffix}"


def _materialize(ctx: Workspace, source: AdoptSource) -> _Item:
    if source.kind == "input":
        if not source.input_id or not is_input_id(source.input_id):
            raise AdoptionError("adopt.input_missing", "The input file no longer exists")
        try:
            stored = ctx.inputs.get(source.input_id)
        except KeyError:
            raise AdoptionError("adopt.input_missing", "The input file no longer exists") from None
        provenance = {"input_file": stored.name, "uploaded": stored.created_at.isoformat()}
        if stored.format == "zip":
            if not source.path:
                raise AdoptionError(
                    "adopt.archive_select", f"Choose the files of {stored.name} to take over", name=stored.name
                )
            entry, _extracted, data = ctx.inputs.member(stored.id, source.path)
            spec = FORMATS[entry.format] if entry.format else None
            name = _named(source.title, PurePosixPath(entry.path).name)
            provenance.update(archive=stored.name, path=entry.path)
        else:
            data = ctx.inputs.data(stored.id)
            spec = FORMATS[stored.format]
            name = _named(source.title, PurePosixPath(stored.name).name)
        if spec is None:
            raise AdoptionError("adopt.unsupported", f"{name} cannot be stored in knowledge", name=name)
        if spec.group == "archive":
            raise AdoptionError("adopt.archive_select", f"Choose the files of {name} to take over", name=name)
        if source.run_id:
            run = ctx.runs.get(source.run_id)
            if run is not None:
                provenance.update(_base_provenance(ctx, run))
                provenance.pop("sources", None)
        media = _TEXT_MEDIA.get(spec.key, spec.media_type)
        if spec.key == "code" and format_of_name(name) is not None:
            media = "text/plain"
        return _Item(
            name=name,
            data=data,
            media_type=media if spec.group != "document" or spec.key == "pdf" else None,
            format=spec.key,
            indexable=spec.indexable,
            editable=False,
            text=None,
            content_kind=None,
            origin="input_file",
            provenance=provenance,
            source_sha256=hashlib.sha256(data).hexdigest(),
        )
    run = _run(ctx, source.run_id)
    if source.kind == "result_file":
        try:
            result, data = ctx.files.content(run.id, source.file_id or "")
        except KeyError:
            raise AdoptionError("adopt.result_file_missing", "The result file no longer exists") from None
        provenance = _base_provenance(ctx, run, result.node_id)
        provenance["result_file"] = result.name
        spec = format_of_name(result.name)
        result_media = {"md": "text/markdown", "csv": "text/csv", "json": "text/plain", "html": "text/html"}.get(
            result.format
        )
        return _Item(
            name=_named(source.title, result.name),
            data=data,
            media_type=result_media or ("application/pdf" if result.format == "pdf" else None),
            format=spec.key if spec else result.format,
            indexable=True,
            editable=False,
            text=None,
            content_kind=None,
            origin="result_file",
            provenance=provenance,
            source_sha256=hashlib.sha256(data).hexdigest(),
        )
    node = next((item for item in run.workflow.nodes if item.id == source.node_id), None)
    state = run.nodes.get(source.node_id or "")
    if node is None or state is None:
        raise AdoptionError("adopt.step_missing", "The step no longer exists")
    provenance = _base_provenance(ctx, run, node.id)
    if source.kind == "proposal":
        proposal = next((item for item in state.proposals if item.id == source.proposal_id), None)
        if proposal is None:
            raise AdoptionError("adopt.proposal_missing", "The proposal no longer exists")
        body = source.text if source.text is not None else proposal.content
        kind: ContentKind = source.content_kind or proposal.content_kind
        title = _safe_title(source.title or proposal.title, node_label(node))
        origin = "proposal"
    else:
        if state.status != "succeeded":
            raise AdoptionError("adopt.step_no_result", "This step has no result", node=node_label(node))
        body = source.text if source.text is not None else to_markdown(state.output)
        kind = source.content_kind or (
            node.agent.knowledge_proposals.content_kind if node.agent is not None else "extracted"
        )
        title = _safe_title(source.title, node_label(node))
        origin = "agent_result"
    if not body.strip():
        raise AdoptionError("adopt.empty", "There is no content to take over")
    if len(body) > _MAX_TEXT:
        raise AdoptionError("adopt.too_large", "The content is too long", limit=_MAX_TEXT)
    provenance["content_kind"] = kind
    text = _document(title, body, kind, provenance)
    data = text.encode("utf-8")
    return _Item(
        name=f"{title}.md",
        data=data,
        media_type="text/markdown",
        format="md",
        indexable=True,
        editable=True,
        text=body,
        content_kind=kind,
        origin=origin,
        provenance=provenance,
        source_sha256=hashlib.sha256(data).hexdigest(),
    )


def _token(item: _Item, collection: str) -> str:
    payload = f"{collection.strip().casefold()}\x00{item.name}\x00{item.source_sha256}"
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:32]


def _duplicate(ctx: Workspace, item: _Item) -> KnowledgeRef | None:
    text_hash = _text_hash(item.text) if item.text is not None else None
    for entry in ctx.knowledge.store.list():
        meta = entry.metadata
        if (
            entry.sha256 == item.source_sha256
            or meta.get("source_sha256") == item.source_sha256
            or (text_hash is not None and meta.get("text_hash") == text_hash)
        ):
            return KnowledgeRef(id=entry.id, name=entry.name, collection=meta.get("collection", ""))
    return None


def _similar(ctx: Workspace, item: _Item, preview: str) -> list[KnowledgeRef]:
    if not item.indexable or not preview.strip():
        return []
    words = _words(preview)
    if len(words) < 8:
        return []
    found: list[KnowledgeRef] = []
    seen: set[str] = set()
    query = " ".join(list(dict.fromkeys(re.findall(r"\w{4,}", preview)))[:12])
    try:
        hits = ctx.knowledge.search(query, None, 8)
    except Exception:  # the full-text index rejects some queries; similarity is only a hint
        return []
    for hit in hits:
        if hit.source in seen or hit.source not in ctx.knowledge.store:
            continue
        seen.add(hit.source)
        other = _words(ctx.knowledge.text_of(hit.source)[:50_000])
        if other and len(words & other) / len(words | other) >= _SIMILAR:
            entry = ctx.knowledge.store.info(hit.source)
            found.append(KnowledgeRef(id=entry.id, name=entry.name, collection=entry.metadata.get("collection", "")))
    return found[:3]


def _preview_text(ctx: Workspace, source: AdoptSource, item: _Item) -> str:
    if item.text is not None:
        return item.text
    if source.kind == "input" and source.input_id:
        try:
            if source.path:
                return ctx.inputs.member(source.input_id, source.path)[1].text
            return ctx.inputs.extracted(source.input_id).text
        except (KeyError, FileFormatError):
            return ""
    if item.format in ("md", "csv", "json", "html", "txt", "code"):
        return item.data.decode("utf-8", errors="replace")
    if item.format in ("docx", "xlsx"):
        from .file_formats import extract

        try:
            return extract(item.name, item.data).text
        except FileFormatError:
            return ""
    if item.format == "pdf":
        from .documents import pdf_pages

        try:
            return "\n\n".join(pdf_pages(item.data))
        except Exception:
            return ""
    return ""


def check(ctx: Workspace, request: AdoptRequest) -> list[AdoptCheck]:
    """What every item would become; stores nothing."""
    results: list[AdoptCheck] = []
    for source in request.items:
        try:
            item = _materialize(ctx, source)
        except (AdoptionError, FileFormatError) as error:
            results.append(AdoptCheck(name=source.title or source.path or "", problem=error.problem))
            continue
        preview = _preview_text(ctx, source, item)
        results.append(
            AdoptCheck(
                name=item.name,
                format=item.format,
                size=len(item.data),
                indexable=item.indexable,
                editable=item.editable,
                preview=preview[:_PREVIEW],
                text=item.text,
                content_kind=item.content_kind,
                duplicate=_duplicate(ctx, item),
                similar=_similar(ctx, item, preview[:_PREVIEW]),
                provenance=item.provenance,
                token=_token(item, request.collection),
            )
        )
    return results


def adopt(ctx: Workspace, request: AdoptConfirm) -> AdoptOutcome:
    """Store the confirmed items; refuses unconfirmed requests and content that changed since the check."""
    if not request.confirmed:
        raise AdoptionError("adopt.not_confirmed", "Taking content over into knowledge needs your confirmation")
    if len(request.tokens) != len(request.items):
        raise AdoptionError("adopt.confirmation_stale", "Check the content again before confirming")
    collection = request.collection.strip()
    prepared: list[tuple[AdoptSource, _Item]] = []
    for source, token in zip(request.items, request.tokens, strict=True):
        item = _materialize(ctx, source)
        if _token(item, collection) != token:
            raise AdoptionError(
                "adopt.confirmation_stale", "The content changed since you checked it; check it again", name=item.name
            )
        prepared.append((source, item))
    outcome = AdoptOutcome()
    stamp = datetime.now(timezone.utc).isoformat()
    for source, item in prepared:
        existing = _duplicate(ctx, item)
        if existing is not None:
            outcome.skipped.append({"name": item.name, "reason": "duplicate", "existing": existing.model_dump()})
            _link(ctx, source, existing.id)
            continue
        extra = {f"origin_{key}": value[:1000] for key, value in item.provenance.items()}
        extra.update(origin=item.origin, origin_adopted_at=stamp, source_sha256=item.source_sha256)
        if item.text is not None:
            extra["text_hash"] = _text_hash(item.text)
        try:
            added = ctx.knowledge.add(
                item.data,
                name=item.name,
                description=request.description.strip()[:500],
                media_type=item.media_type,
                collection=collection,
                extra=extra,
            )
        except (ValueError, NodestroError) as error:
            code = error.code if isinstance(error, NodestroError) else "adopt.store_failed"
            outcome.skipped.append({"name": item.name, "reason": code, "message": str(error)[:300]})
            continue
        outcome.added.append(added)
        _link(ctx, source, added.id)
    return outcome


def _link(ctx: Workspace, source: AdoptSource, knowledge_id: str) -> None:
    """Remember the knowledge file at its origin (input file, proposal)."""
    if source.kind == "input" and source.input_id:
        ctx.inputs.link_knowledge(source.input_id, knowledge_id)
    elif source.kind == "proposal" and source.run_id:
        run = ctx.runs.get(source.run_id)
        if run is None:
            return
        state = run.nodes.get(source.node_id or "")
        proposal = next((item for item in state.proposals if item.id == source.proposal_id), None) if state else None
        if proposal is not None and proposal.adopted_file_id is None:
            proposal.adopted_file_id = knowledge_id
            if not ctx.runs.is_live(run.id):
                ctx.store.put("runs", run.id, run)
